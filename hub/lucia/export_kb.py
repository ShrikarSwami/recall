"""Export the knowledge base as JSON for the simulator's offline mock mode.

    cd hub && uv run python -m lucia.export_kb      # writes ../sim/mock-kb.json
"""
from __future__ import annotations

import json

from .config import KNOWLEDGE_DIR, ROOT, fill, load_config, placeholders
from .knowledge import Knowledge, load


def export_kb(kb: Knowledge, cfg: dict) -> dict:
    vals = placeholders(cfg)
    return {
        "app": cfg["appName"], "wake": cfg["wakeWord"], "hint": fill(cfg["idleHint"], vals),
        "patient": vals["patient"], "caregiver": vals["caregiver"], "currentPlace": cfg.get("currentPlace"),
        "people": {pid: {"name": p.name, "first": p.first, "aliases": p.aliases, "intro": fill(p.intro, vals)}
                   for pid, p in kb.people.items()},
        "places": kb.places,
        "entries": [{"scope": e.scope, "subject": e.subject, "questions": e.questions,
                     "answer": fill(e.answer, vals)} for e in kb.entries],
    }


if __name__ == "__main__":
    cfg = load_config(ROOT / "config" / "app.example.json")  # never export the private local config
    data = json.dumps(export_kb(load(KNOWLEDGE_DIR), cfg), indent=1)
    (ROOT / "sim" / "mock-kb.json").write_text(data)
    # .js copy so the simulator also works when opened straight from disk (file://, no server)
    (ROOT / "sim" / "mock-kb.js").write_text("// generated by: cd hub && uv run python -m lucia.export_kb\nwindow.MOCK_KB = " + data + ";\n")
    print("wrote sim/mock-kb.json and sim/mock-kb.js")
